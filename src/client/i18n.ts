/**
 * Pick the UI language: the plugin setting wins unless it is `auto`, in which
 * case DSH's active locale decides (`ja*` → ja, `zh*` → zh, otherwise en).
 */
export function resolveLanguage(
  setting: UiLanguage | undefined,
  dshLocale: string | undefined,
  browserLanguages: readonly string[] = navigatorLanguages(),
): Language {
  if (setting === 'en' || setting === 'ja' || setting === 'zh') return setting
  const active = (dshLocale ?? '').toLowerCase()
  if (active.startsWith('ja')) return 'ja'
  if (active.startsWith('zh')) return 'zh'
  // DSH ships English and Chinese only, so a Japanese browser lands on English
  // there; prefer the browser's own first choice between the languages we have.
  for (const tag of browserLanguages) {
    const lower = tag.toLowerCase()
    if (lower.startsWith('ja')) return 'ja'
    if (lower.startsWith('en') || lower.startsWith('zh')) break
  }
  return 'en'
}

function navigatorLanguages(): readonly string[] {
  const nav = (globalThis as { navigator?: { languages?: readonly string[]; language?: string } }).navigator
  if (!nav) return []
  if (Array.isArray(nav.languages) && nav.languages.length > 0) return nav.languages
  return typeof nav.language === 'string' ? [nav.language] : []
}

export function interpolate(template: string, params?: MessageParams): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

export interface Translator {
  readonly lang: Language
  readonly intlLocale: string
  t(key: MessageKey, params?: MessageParams): string
  /** Look up a key built at runtime (notice keys, error codes); undefined when unknown. */
  lookup(key: string, params?: MessageParams): string | undefined
}

const cache = new Map<Language, Translator>()

export function getTranslator(lang: Language): Translator {
  const hit = cache.get(lang)
  if (hit) return hit
  const dict = DICTIONARIES[lang]
  const translator: Translator = {
    lang,
    intlLocale: INTL_LOCALE[lang],
    t: (key, params) => interpolate(dict[key] ?? en[key] ?? key, params),
    lookup: (key, params) => {
      if (!Object.hasOwn(dict, key)) return undefined
      return interpolate(dict[key as MessageKey], params)
    },
  }
  cache.set(lang, translator)
  return translator
}

/** Localized text for a Host error, falling back to the server's English message. */
export function errorText(tr: Translator, error: { readonly code: string; readonly message?: string }): string {
  return tr.lookup(`error.${error.code}`) ?? (error.message?.trim() || tr.t('error.generic'))
}

/** Localized text for a scan notice, falling back to the server's English text. */
export function noticeText(tr: Translator, notice: { readonly key: string; readonly text: string }): string {
  return tr.lookup(`notice.${notice.key}`) ?? notice.text
}
