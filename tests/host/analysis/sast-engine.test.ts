import { describe, expect, it } from 'vitest'
import { runSast } from '../../../src/host/analysis/sast/engine.ts'
import { fileOf, snapshotOf } from './helpers.ts'
import { hits, MODES, ofRule, sast } from './sast-helpers.ts'

const VULN_HANDLER = [
  "const { exec } = require('child_process')",
  "app.get('/x', (req, res) => {",
  '  exec("ping -c1 " + req.query.host)',
  '})',
].join('\n')

describe.each(MODES)('SAST engine (%s mode)', (_mode, handle) => {
  it('reports analyzer status and sorted signals', async () => {
    const run = await runSast(snapshotOf({ 'b.js': VULN_HANDLER, 'a.js': VULN_HANDLER }), { astGrep: handle })
    expect(run.status).toEqual({ id: 'sast', available: true, source: 'builtin' })
    expect(run.signals.map(s => s.location.path)).toEqual(['a.js', 'b.js'])
    expect(run.durationMs).toBeGreaterThanOrEqual(0)
  })

  it('caps severity and confidence for test files', async () => {
    const signals = await sast({ 'test/server.test.js': VULN_HANDLER, 'src/server.js': VULN_HANDLER }, handle)
    const byPath = Object.fromEntries(ofRule(signals, 'js.command-injection').map(s => [s.location.path, s]))
    expect(byPath['src/server.js']).toMatchObject({ severity: 'critical', confidence: 'high' })
    expect(byPath['test/server.test.js']).toMatchObject({ severity: 'low', confidence: 'low' })
    expect(byPath['test/server.test.js']?.message).toMatch(/test, fixture or example/)
  })

  it('skips generated files', async () => {
    const run = await runSast(
      {
        ...snapshotOf({}),
        files: new Map([['gen/api.js', fileOf('gen/api.js', `// @generated by tool\n${VULN_HANDLER}`)]]),
      },
      { astGrep: handle },
    )
    expect(run.signals).toEqual([])
  })

  it('keeps fingerprints stable when lines shift, and distinct for different code', async () => {
    const [a] = await sast({ 'src/s.js': VULN_HANDLER }, handle)
    const shifted = `// a new header comment\n\n\n${VULN_HANDLER.replace('  exec(', '    exec(')}`
    const [b] = await sast({ 'src/s.js': shifted }, handle)
    const [c] = await sast({ 'src/s.js': VULN_HANDLER.replace('req.query.host', 'req.query.target') }, handle)
    expect(a?.location.startLine).toBe(3)
    expect(b?.location.startLine).toBe(6)
    expect(b?.fingerprintParts).toEqual(a?.fingerprintParts)
    expect(a?.fingerprintParts).toEqual(['js.command-injection', 'src/s.js', 'exec("ping -c1 " + req.query.host)'])
    expect(c?.fingerprintParts).not.toEqual(a?.fingerprintParts)
  })

  it('deduplicates by rule, path and line, keeping the strongest signal', async () => {
    const code = "app.get('/x', (req, res) => { el.innerHTML = req.query.a; el.innerHTML = other })\n"
    const signals = await sast({ 'src/a.js': code }, handle)
    expect(hits(signals, 'js.xss')).toEqual(['1 vulnerability'])
  })

  it('redacts secrets in snippets and messages', async () => {
    const token = ['ghp', '_', 'aB3dE5fG7hJ9kL1mN3pQ5rS7tU9vW1xY3zA5'].join('')
    const code = [
      "app.get('/x', async (req, res) => {",
      `  await fetch(req.query.url, { headers: { authorization: 'token ${token}' } })`,
      '})',
    ].join('\n')
    const [s] = ofRule(await sast({ 'src/a.js': code }, handle), 'js.ssrf')
    expect(s?.snippet).toContain('[REDACTED:github-token]')
    expect(JSON.stringify(s)).not.toContain(token)
  })

  it('limits snippets to five lines', async () => {
    const code = [
      "app.get('/x', async (req, res) => {",
      '  await db.query(',
      "    'SELECT * FROM users ' +",
      "    'WHERE a = 1 ' +",
      "    'AND b = 2 ' +",
      "    'AND c = 3 ' +",
      "    'AND name = ' + req.query.name,",
      '  )',
      '})',
    ].join('\n')
    const [s] = ofRule(await sast({ 'src/a.js': code }, handle), 'js.sql-injection')
    expect(s?.location).toEqual({ path: 'src/a.js', startLine: 2, endLine: 8 })
    expect(s?.snippet.split('\n')).toHaveLength(5)
  })

  it('honors an aborted signal', async () => {
    const files: Record<string, string> = {}
    for (let i = 0; i < 60; i++) files[`src/f${i}.js`] = VULN_HANDLER
    const controller = new AbortController()
    controller.abort(new Error('stop'))
    await expect(runSast(snapshotOf(files), { astGrep: handle, signal: controller.signal })).rejects.toThrow('stop')
    const late = new AbortController()
    const pending = runSast(snapshotOf(files), { astGrep: handle, signal: late.signal })
    late.abort(new Error('late stop'))
    await expect(pending).rejects.toThrow('late stop')
  })

  it('scans scripts embedded in Vue/HTML files at their original lines', async () => {
    const vue = [
      '<template><div>{{ msg }}</div></template>',
      '<script>',
      'export default {',
      '  mounted() { document.getElementById("o").innerHTML = location.hash }',
      '}',
      '</script>',
    ].join('\n')
    const signals = await sast({ 'src/App.vue': vue }, handle)
    expect(hits(signals, 'js.xss')).toEqual(['4 vulnerability'])
  })
})

describe('config rules', () => {
  it('flags risky Dockerfile instructions', async () => {
    const signals = await sast(
      {
        Dockerfile: [
          'FROM node:22',
          'ADD https://example.com/tool.tar.gz /opt/',
          'ADD --checksum=sha256:abc https://example.com/ok.tar.gz /opt/',
          'RUN curl -fsSL https://get.example.sh \\',
          '    | sh',
          'RUN curl -fsSLo /tmp/x https://example.com/x && sha256sum -c x.sha256',
          'ENV DB_PASSWORD=sup3rs3cretvalue API_URL=https://api.example.com',
          // biome-ignore lint/suspicious/noTemplateCurlyInString: Dockerfile variable syntax under test
          'ENV API_TOKEN ${API_TOKEN}',
          'ARG NPM_TOKEN',
          'ENV SECRET_KEY_FILE=/run/secrets/key',
          'COPY . .',
        ].join('\n'),
      },
      undefined,
    )
    expect(signals.map(s => `${s.ruleId} ${s.location.startLine}`)).toEqual([
      'docker.add-remote-url 2',
      'docker.curl-pipe-shell 4',
      'docker.secret-in-env 7',
    ])
    const env = ofRule(signals, 'docker.secret-in-env')[0]!
    expect(env.snippet).toBe('ENV DB_PASSWORD=*** API_URL=https://api.example.com')
    expect(JSON.stringify(env)).not.toContain('sup3rs3cretvalue')
  })

  it('does not flag a Dockerfile without USER', async () => {
    expect(await sast({ Dockerfile: 'FROM node:22\nCOPY . .\nCMD ["node", "index.js"]\n' }, undefined)).toEqual([])
  })

  it('flags privileged and host-network containers in compose and Kubernetes files', async () => {
    const signals = await sast(
      {
        'docker-compose.yml':
          'services:\n  app:\n    privileged: true\n    network_mode: host\n  db:\n    privileged: false\n',
        'k8s/deploy.yaml': [
          'apiVersion: apps/v1',
          'kind: Deployment',
          'spec:',
          '  template:',
          '    spec:',
          '      hostNetwork: true',
          '      containers:',
          '        - name: a',
          '          securityContext:',
          '            privileged: true',
          '            allowPrivilegeEscalation: true',
          '        - name: b',
          '          securityContext:',
          '            allowPrivilegeEscalation: false',
        ].join('\n'),
        'config/app.yaml': 'privileged: true\n',
      },
      undefined,
    )
    expect(signals.map(s => `${s.location.path}:${s.location.startLine} ${s.ruleId} ${s.severity}`)).toEqual([
      'docker-compose.yml:3 container.privileged medium',
      'docker-compose.yml:4 container.host-network low',
      'k8s/deploy.yaml:6 container.host-network low',
      'k8s/deploy.yaml:10 container.privileged medium',
      'k8s/deploy.yaml:11 k8s.allow-privilege-escalation low',
    ])
  })
})
